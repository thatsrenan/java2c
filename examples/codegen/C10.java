public class Castes {
    public static void main(String[] args) {
        int i = 7;
        double d = i;
        float f = (float) d / 2;
        char c = (char) (i + 60);
        int back = c;
        System.out.println(d);
        System.out.println(f);
        System.out.println(c);
        System.out.println(back);
        System.out.println((int) (d * 2));
    }
}
